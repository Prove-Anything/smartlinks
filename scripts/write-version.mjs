// Writes src/version.ts from package.json, so the SDK can say which release it is (SmartLinks-SDK header).
// Runs first in `npm run build`.
import { readFileSync, writeFileSync } from "node:fs"
const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"))
const out = `// Generated by scripts/write-version.mjs from package.json. Do not edit.\nexport const SDK_VERSION = ${JSON.stringify(version)}\n`
const file = new URL("../src/version.ts", import.meta.url)
let current = ""
try { current = readFileSync(file, "utf8") } catch {}
if (current !== out) writeFileSync(file, out)
console.log(`SDK version ${version}`)
